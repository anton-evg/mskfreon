export const indexableRoutes = Object.keys(seoData).filter((route) => !seoData[route].noindex);

export function normalizePathname(pathname) {
  const normalized = pathname.replace(/\/$/, "") || "/";
  return seoData[normalized] ? normalized : "/404";
}

export function getSeoData(pathname) {
  const route = normalizePathname(pathname);
  const page = seoData[route];
  const canonical = route === "/404" ? `${siteUrl}/404` : `${siteUrl}${route === "/" ? "/" : route}`;
  const image = new URL(socialImage, siteUrl).href;

  return { ...page, route, canonical, image, type: page.type || "website" };
}
